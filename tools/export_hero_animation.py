"""Export the editable four-pose sheet and registration data; --check never publishes."""
import argparse
import json
from pathlib import Path
import subprocess
import sys
import tempfile
from PIL import Image

REPO = Path(__file__).resolve().parent.parent
PROJECT = REPO / '새-게임-프로젝트'
SOURCE = REPO / 'art_source/hero'
ATLAS = PROJECT / 'assets/art/actor_motion_20261005/reclaimer_actions_v1.png'
DATA = PROJECT / 'redesign/hero_pose_data.gd'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    manifest = json.loads((SOURCE / 'poses.json').read_text(encoding='utf-8'))
    cell = manifest['cell']
    lines = ['extends RefCounted', '# Generated by tools/export_hero_animation.py. Edit art_source/hero/poses.json.',
             f'const CELL := Vector2({cell[0]}, {cell[1]})', f'const SCALE := {manifest["scale"]}', 'const FRAMES := {']
    assert set(manifest['poses']) == {'aim', 'recoil', 'reload_open', 'reload_seat'}
    for name, pose in manifest['poses'].items():
        for key in ('anchor', 'muzzle'):
            assert all(0 <= pose[key][i] < cell[i] for i in range(2)), (name, key)
        values = ', '.join(f'"{key}": Vector2({value[0]}, {value[1]})' for key, value in pose.items())
        lines.append(f'\t"{name}": {{{values}}},')
    lines.append('}')
    text = '\n'.join(lines) + '\n'
    staging = REPO / 'qa_runtime/hero_export'
    staging.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix='export_', dir=staging) as folder:
        exported = Path(folder) / 'atlas.png'
        metadata = Path(folder) / 'export.json'
        run = subprocess.run([sys.executable, str(REPO / 'tools/pixel_editor.py'), '--batch',
                              str(SOURCE / manifest['source']), '--sheet', str(exported),
                              '--data', str(metadata), '--format', 'json-array'],
                             capture_output=True, timeout=60)
        if run.returncode or not exported.exists():
            raise RuntimeError(run.stdout.decode(errors='replace') + run.stderr.decode(errors='replace'))
        info = json.loads(metadata.read_text(encoding='utf-8'))
        assert len(info['frames']) == 1, 'Source is a four-pose atlas, not a timeline; keep its layout.'
        with Image.open(exported) as image:
            assert image.size == (cell[0]*2, cell[1]*2), 'Unexpected atlas dimensions'
            pixels = image.convert('RGBA').tobytes()
        if args.check:
            with Image.open(ATLAS) as current:
                assert current.convert('RGBA').tobytes() == pixels, 'Source and runtime pixels differ; export first'
            assert DATA.read_text(encoding='utf-8') == text, 'Registration data is stale; export first'
        else:
            # Publish only after editor export and layout validation both succeed.
            identical = False
            if ATLAS.exists():
                with Image.open(ATLAS) as current:
                    identical = current.size == (cell[0]*2, cell[1]*2) and current.convert('RGBA').tobytes() == pixels
            # Preserve approved PNG provenance/hash when only encoding differs.
            if not identical:
                ATLAS.write_bytes(exported.read_bytes())
            DATA.write_text(text, encoding='utf-8')
    print('HERO EXPORT PASS: four poses, exact source/runtime RGBA, anchors and muzzle data' if args.check
          else 'HERO EXPORT COMPLETE: atlas and Godot registration data updated')


if __name__ == '__main__':
    main()
